
"use client";

import { useEffect, useState } from "react";

import { Check, X } from "lucide-react";

import type { QuestionRendererProps } from "@/renderer/QuestionRendererTypes";

import "@/styles/worksheet.css";

type StrategyData = {
  questionType?: string;
  originalNumber?: number;
  reversedNumber?: number;
  equation?: string;
  minuend?: number;
  subtrahend?: number;
  options?: string[];
  missingDigitsSum?: number;
  digitTiles?: number[];
  instructions?: string;
};

type EquationPair = {
  minuendTileId: string;
  subtrahendTileId: string;
};

type DigitClueAnswer = {
  firstMissingDigit?: number | null;
  secondMissingDigit?: number | null;
};

type MaximumDifferenceAnswer = {
  minuend?: number;
  subtrahend?: number;
  difference?: number;
};

function parseJson<T>(value: string, fallback: T): T {
  try {
    return JSON.parse(value) as T;
  } catch {
    return fallback;
  }
}

function parseEquationPairs(value: string): EquationPair[] {
  const parsed = parseJson<unknown>(value, []);

  if (!Array.isArray(parsed)) return [];

  return parsed.filter(
    (item): item is EquationPair =>
      typeof item === "object" &&
      item !== null &&
      typeof (item as EquationPair).minuendTileId === "string" &&
      typeof (item as EquationPair).subtrahendTileId === "string",
  );
}

function getDigit(value: number, position: number): number {
  return Math.floor(value / position) % 10;
}

export default function SubtractionNumberPropertiesLabQuestion({
  question,
  data,
  userAnswer,
  showAnswers,
  onAnswerChange,
  correctAnswers,
}: QuestionRendererProps) {
  const properties = data as StrategyData;

  const code = (
    question.questionTypeCode?.trim() ||
    properties.questionType?.trim() ||
    ""
  ).toUpperCase();

  const answer =
    userAnswer === undefined || userAnswer === null
      ? ""
      : String(userAnswer);

  const expectedAnswer = String(correctAnswers?.[0] ?? "");

  const isReverse =
    code === "NUMERIC_REVERSE_DIGIT_DIFFERENCE";

  const isBorrowing =
    code === "NUMERIC_BORROWING_PREDICTOR";

  const isDigitClue =
    code === "NUMERIC_DIGIT_CLUE_RECONSTRUCTION";

  const isMaximumDifference =
    code === "NUMERIC_MAXIMUM_DIFFERENCE";

  const hasAnswer = answer.trim().length > 0;

  // Structured answers generated by the backend.
  const digitAnswer = parseJson<DigitClueAnswer>(answer, {});
  const correctDigitAnswer = parseJson<DigitClueAnswer>(
    expectedAnswer,
    {},
  );

  const maximumAnswer = parseJson<MaximumDifferenceAnswer>(answer, {});
  const correctMaximumAnswer = parseJson<MaximumDifferenceAnswer>(
    expectedAnswer,
    {},
  );

  const pairs = parseEquationPairs(answer);
  const correctPairs = parseEquationPairs(expectedAnswer);

  const numericCorrect =
    hasAnswer &&
    Number.isFinite(Number(answer)) &&
    Number(answer) === Number(expectedAnswer);

  const borrowingCorrect =
    hasAnswer &&
    answer.trim().toLowerCase() === expectedAnswer.trim().toLowerCase();

  const digitClueCorrect =
    typeof digitAnswer.firstMissingDigit === "number" &&
    typeof digitAnswer.secondMissingDigit === "number" &&
    typeof correctDigitAnswer.firstMissingDigit === "number" &&
    typeof correctDigitAnswer.secondMissingDigit === "number" &&
    digitAnswer.firstMissingDigit === correctDigitAnswer.firstMissingDigit &&
    digitAnswer.secondMissingDigit === correctDigitAnswer.secondMissingDigit;

  const samePairs = (
    first: EquationPair[],
    second: EquationPair[],
  ) => {
    if (first.length === 0 || first.length !== second.length) {
      return false;
    }

    const key = (pair: EquationPair) =>
      `${pair.minuendTileId}:${pair.subtrahendTileId}`;

    const left = first.map(key).sort();
    const right = second.map(key).sort();

    return left.every((value, index) => value === right[index]);
  };

  const maximumCorrect =
    typeof maximumAnswer.minuend === "number" &&
    typeof maximumAnswer.subtrahend === "number" &&
    typeof maximumAnswer.difference === "number" &&
    maximumAnswer.minuend === correctMaximumAnswer.minuend &&
    maximumAnswer.subtrahend === correctMaximumAnswer.subtrahend &&
    maximumAnswer.difference === correctMaximumAnswer.difference;

  const isCorrect = isReverse
    ? numericCorrect
    : isBorrowing
      ? borrowingCorrect
      : isDigitClue
        ? digitClueCorrect
        : isMaximumDifference
          ? maximumCorrect
          : false;

  // ------------------------------------------------------
  // DIGIT CLUE RECONSTRUCTION
  // Submit the exact backend property names.
  // ------------------------------------------------------

  const updateMissingDigit = (
    field: "firstMissingDigit" | "secondMissingDigit",
    value: string,
  ) => {
    if (showAnswers) return;

    const next: DigitClueAnswer = {
      firstMissingDigit: digitAnswer.firstMissingDigit ?? null,
      secondMissingDigit: digitAnswer.secondMissingDigit ?? null,
      [field]: value === "" ? null : Number(value),
    };

    onAnswerChange(JSON.stringify(next));
  };

  // ------------------------------------------------------
  // MAXIMUM DIFFERENCE
  // Four selected tile positions form two two-digit numbers.
  // ------------------------------------------------------

  const tiles = properties.digitTiles ?? [];

  const [digitSlots, setDigitSlots] = useState<Array<number | null>>([
    null,
    null,
    null,
    null,
  ]);

  const createSolutionSlots = (
    solution: MaximumDifferenceAnswer,
  ): Array<number | null> => {
    if (
      typeof solution.minuend !== "number" ||
      typeof solution.subtrahend !== "number"
    ) {
      return [null, null, null, null];
    }

    const digits = [
      Math.floor(solution.minuend / 10),
      solution.minuend % 10,
      Math.floor(solution.subtrahend / 10),
      solution.subtrahend % 10,
    ];

    const usedIndexes = new Set<number>();

    return digits.map((digit) => {
      const index = tiles.findIndex(
        (tile, tileIndex) =>
          tile === digit && !usedIndexes.has(tileIndex),
      );

      if (index < 0) return null;

      usedIndexes.add(index);
      return index;
    });
  };

  // Restore the selection if an existing answer is loaded.
  useEffect(() => {
    if (!isMaximumDifference) {
      setDigitSlots([null, null, null, null]);
      return;
    }

    if (!answer) {
      setDigitSlots([null, null, null, null]);
      return;
    }

    const parsed = parseJson<MaximumDifferenceAnswer>(answer, {});

    if (
      typeof parsed.minuend === "number" &&
      typeof parsed.subtrahend === "number"
    ) {
      setDigitSlots(createSolutionSlots(parsed));
    }
  }, [question.generatedQuestionId, code, answer]);

  const updateDigitSlots = (next: Array<number | null>) => {
    setDigitSlots(next);

    if (next.some((index) => index === null)) {
      onAnswerChange("");
      return;
    }

    const values = next.map(
      (index) => tiles[index as number],
    );

    if (values.some((value) => value === undefined)) {
      onAnswerChange("");
      return;
    }

    const minuend = values[0] * 10 + values[1];
    const subtrahend = values[2] * 10 + values[3];

    onAnswerChange(
      JSON.stringify({
        minuend,
        subtrahend,
        difference: minuend - subtrahend,
      }),
    );
  };

  const selectDigit = (tileIndex: number) => {
    if (showAnswers || digitSlots.includes(tileIndex)) return;

    const firstEmpty = digitSlots.findIndex((index) => index === null);

    if (firstEmpty < 0) return;

    const next = [...digitSlots];
    next[firstEmpty] = tileIndex;

    updateDigitSlots(next);
  };

  const clearDigitSlot = (slotIndex: number) => {
    if (showAnswers || digitSlots[slotIndex] === null) return;

    const next = [...digitSlots];
    next[slotIndex] = null;

    updateDigitSlots(next);
  };

  const resetDigits = () => {
    if (showAnswers) return;

    setDigitSlots([null, null, null, null]);
    onAnswerChange("");
  };

  const visibleSlots =
    showAnswers && correctMaximumAnswer.minuend !== undefined
      ? createSolutionSlots(correctMaximumAnswer)
      : digitSlots;

  // ------------------------------------------------------
  // COMMON NUMERIC INPUT STYLE
  // ------------------------------------------------------

  const inputClass = [
    "subtraction-number-properties-lab__input",
    showAnswers && hasAnswer
      ? isCorrect
        ? "subtraction-number-properties-lab__input--correct"
        : "subtraction-number-properties-lab__input--wrong"
      : "",
  ].filter(Boolean).join(" ");

  return (
    <section className="subtraction-number-properties-lab">
      {/* The question prompt comes directly from the backend. */}
      <h3 className="generated-question__text">
        {question.questionText}
      </h3>

      {/* 1. REVERSE-DIGIT DIFFERENCE */}

      {isReverse && (
        <div className="subtraction-number-properties-lab__panel">
        

          <div className="subtraction-number-properties-lab__equation">
            {properties.equation}
          </div>

          <div className="subtraction-number-properties-lab__input-row">
            <label htmlFor={`reverse-${question.generatedQuestionId}`}>
              Difference
            </label>

            <input
              id={`reverse-${question.generatedQuestionId}`}
              type="number"
              inputMode="numeric"
              placeholder="?"
              value={answer}
              disabled={showAnswers}
              className={inputClass}
              onChange={(event) => onAnswerChange(event.target.value)}
            />

            {showAnswers && hasAnswer && (
              isCorrect
                ? <Check size={20} className="subtraction-number-properties-lab__correct-icon" />
                : <X size={20} className="subtraction-number-properties-lab__wrong-icon" />
            )}
          </div>

          {showAnswers && (
            <p className="subtraction-number-properties-lab__solution">
              Difference: <strong>{expectedAnswer}</strong>
            </p>
          )}
        </div>
      )}

      {/* 2. BORROWING PREDICTOR */}

      {isBorrowing && (
        <div className="subtraction-number-properties-lab__panel">
          <div className="subtraction-number-properties-lab__equation subtraction-number-properties-lab__equation--large">
            {properties.equation}
          </div>

          <div className="subtraction-number-properties-lab__choice-grid">
            {(properties.options ?? ["Yes", "No"]).map((option) => {
              const selected =
                answer.trim().toLowerCase() === option.toLowerCase();

              const expected =
                expectedAnswer.trim().toLowerCase() === option.toLowerCase();

              return (
                <button
                  type="button"
                  key={option}
                  disabled={showAnswers}
                  aria-pressed={selected}
                  className={[
                    "subtraction-number-properties-lab__choice",
                    selected
                      ? "subtraction-number-properties-lab__choice--selected"
                      : "",
                    showAnswers && expected
                      ? "subtraction-number-properties-lab__choice--correct"
                      : "",
                    showAnswers && selected && !expected
                      ? "subtraction-number-properties-lab__choice--wrong"
                      : "",
                  ].filter(Boolean).join(" ")}
                  onClick={() => onAnswerChange(option)}
                >
                  {option}
                  {showAnswers && expected && <Check size={18} />}
                  {showAnswers && selected && !expected && <X size={18} />}
                </button>
              );
            })}
          </div>

          {showAnswers && (
            <p className="subtraction-number-properties-lab__solution">
              Borrowing required: <strong>{expectedAnswer}</strong>
            </p>
          )}
        </div>
      )}

      {/* 3. DIGIT CLUE RECONSTRUCTION */}

      {isDigitClue && (
        <div className="subtraction-number-properties-lab__panel">
          <div className="subtraction-number-properties-lab__equation subtraction-number-properties-lab__equation--large">
            {properties.equation}
          </div>

          <p className="subtraction-number-properties-lab__clue">
            The two missing digits add up to{" "}
            <strong>{properties.missingDigitsSum}</strong>.
          </p>

          <div className="subtraction-number-properties-lab__digit-inputs">
            <label>
              First missing digit
              <input
                type="number"
                inputMode="numeric"
                min={0}
                max={9}
                placeholder="0–9"
                value={digitAnswer.firstMissingDigit ?? ""}
                disabled={showAnswers}
                className={inputClass}
                onChange={(event) =>
                  updateMissingDigit("firstMissingDigit", event.target.value)
                }
              />
            </label>

            <label>
              Second missing digit
              <input
                type="number"
                inputMode="numeric"
                min={0}
                max={9}
                placeholder="0–9"
                value={digitAnswer.secondMissingDigit ?? ""}
                disabled={showAnswers}
                className={inputClass}
                onChange={(event) =>
                  updateMissingDigit("secondMissingDigit", event.target.value)
                }
              />
            </label>
          </div>

          {showAnswers && (
            <p className="subtraction-number-properties-lab__solution">
              Correct digits:{" "}
              <strong>{correctDigitAnswer.firstMissingDigit}</strong>
              {" and "}
              <strong>{correctDigitAnswer.secondMissingDigit}</strong>
            </p>
          )}
        </div>
      )}

      {/* 4. MAXIMUM DIFFERENCE */}

      {isMaximumDifference && (
        <div className="subtraction-number-properties-lab__panel">
          <div className="subtraction-number-properties-lab__tile-bank">
            {(properties.digitTiles ?? []).map((digit, index) => {
              const isUsed = digitSlots.includes(index);

              return (
                <button
                  type="button"
                  key={`${digit}-${index}`}
                  disabled={showAnswers || isUsed}
                  className={[
                    "subtraction-number-properties-lab__digit-tile",
                    isUsed
                      ? "subtraction-number-properties-lab__digit-tile--used"
                      : "",
                  ].filter(Boolean).join(" ")}
                  onClick={() => selectDigit(index)}
                >
                  {digit}
                </button>
              );
            })}
          </div>

          <div className="subtraction-number-properties-lab__number-builder">
            {[
              { label: "Minuend", slots: [0, 1] },
              { label: "Subtrahend", slots: [2, 3] },
            ].map((group) => (
              <div
                key={group.label}
                className="subtraction-number-properties-lab__number-group"
              >
                <span>{group.label}</span>

                <div>
                  {group.slots.map((slotIndex) => {
                    const selectedIndex = visibleSlots[slotIndex];

                    return (
                      <button
                        type="button"
                        key={slotIndex}
                        disabled={
                          showAnswers || selectedIndex === null
                        }
                        className="subtraction-number-properties-lab__number-slot"
                        onClick={() => clearDigitSlot(slotIndex)}
                        aria-label={`Clear ${group.label} digit ${slotIndex % 2 + 1}`}
                      >
                        {selectedIndex === null
                          ? "?"
                          : tiles[selectedIndex]}
                      </button>
                    );
                  })}
                </div>
              </div>
            ))}
          </div>

          <div className="subtraction-number-properties-lab__equation subtraction-number-properties-lab__equation--large">
            {visibleSlots[0] === null || visibleSlots[1] === null
              ? "??"
              : `${tiles[visibleSlots[0]]}${tiles[visibleSlots[1]]}`}
            {" − "}
            {visibleSlots[2] === null || visibleSlots[3] === null
              ? "??"
              : `${tiles[visibleSlots[2]]}${tiles[visibleSlots[3]]}`}
            {showAnswers &&
            typeof correctMaximumAnswer.difference === "number"
              ? ` = ${correctMaximumAnswer.difference}`
              : ""}
          </div>

          {!showAnswers && (
            <button
              type="button"
              className="subtraction-number-properties-lab__reset"
              onClick={resetDigits}
            >
              Reset digits
            </button>
          )}

          {showAnswers && (
            <p className="subtraction-number-properties-lab__solution">
              Maximum difference:{" "}
              <strong>{correctMaximumAnswer.minuend}</strong>
              {" − "}
              <strong>{correctMaximumAnswer.subtrahend}</strong>
              {" = "}
              <strong>{correctMaximumAnswer.difference}</strong>
            </p>
          )}
        </div>
      )}

      {/* FEEDBACK */}

      {showAnswers && (
        <p
          className={[
            "subtraction-number-properties-lab__feedback",
            isCorrect
              ? "subtraction-number-properties-lab__feedback--correct"
              : "subtraction-number-properties-lab__feedback--wrong",
          ].join(" ")}
          role="status"
        >
          {isCorrect
            ? "Correct answer!"
            : "Compare your answer with the solution shown above."}
        </p>
      )}
    </section>
  );
}

import React from "react";
import "@/styles/worksheet.css";

import type { QuestionRendererProps } from "@/renderer/QuestionRendererTypes";

type PredictOddEvenData = {
  renderKey?: string;
  questionType?: string;
  title?: string;
  operation?: string;
  operationLabel?: string;
  startingNumber?: number;
  changeBy?: number;
  result?: number;
  equation?: string;
  options?: string[];
};

export default function PredictTheOddEvenChange({
  data,
  userAnswer,
  showAnswers,
  onAnswerChange,
}: QuestionRendererProps) {
  const d = data as PredictOddEvenData;

  // Use the question type and values generated by the backend.
  const questionType = d.questionType ?? "";
  const isAddition = questionType === "ADD_ONE";
  const isSubtraction = questionType === "SUBTRACT_ONE";

  const options = d.options ?? ["Odd", "Even"];
  const currentAnswer =
    userAnswer == null ? "" : String(userAnswer);

  const result = Number(d.result ?? 0);
  const correctAnswer = result % 2 === 0 ? "Even" : "Odd";

  if (!isAddition && !isSubtraction) {
    return (
      <section className="predict_the_odd_even_change__card">
        <p className="predict_the_odd_even_change__hint">
          Unsupported question type.
        </p>
      </section>
    );
  }

  return (
    <section className="predict_the_odd_even_change__card">
      <header className="predict_the_odd_even_change__header">
        <span
          className={`predict_the_odd_even_change__badge ${
            isAddition
              ? "predict_the_odd_even_change__badge--addition"
              : "predict_the_odd_even_change__badge--subtraction"
          }`}
        >
          {isAddition ? "ONE MORE" : "ONE LESS"}
        </span>

        {/* <h3 className="predict_the_odd_even_change__title">
          {d.title ?? "One More or One Less"}
        </h3> */}
      </header>

      <div className="predict_the_odd_even_change__equation">
        <span className="predict_the_odd_even_change__number">
          {d.startingNumber ?? 0}
        </span>

        <span className="predict_the_odd_even_change__operator">
          {isAddition ? "+" : "−"}
        </span>

        <span className="predict_the_odd_even_change__number">
          {d.changeBy ?? 1}
        </span>

        <span className="predict_the_odd_even_change__equals">
          =
        </span>

        <span className="predict_the_odd_even_change__result">
          {d.result ?? 0}
        </span>
      </div>

      <p className="predict_the_odd_even_change__instruction">
        Is the result odd or even?
      </p>

      <div className="predict_the_odd_even_change__choices">
        {options.map((option) => {
          const selected = currentAnswer === option;
          const correct = showAnswers && option === correctAnswer;

          const className = [
            "predict_the_odd_even_change__choice",
            selected
              ? "predict_the_odd_even_change__choice--selected"
              : "",
            correct
              ? "predict_the_odd_even_change__choice--correct"
              : "",
          ]
            .filter(Boolean)
            .join(" ");

          return (
            <button
              type="button"
              key={option}
              className={className}
              onClick={() => onAnswerChange(option)}
              aria-pressed={selected}
            >
              <span className="predict_the_odd_even_change__choice-icon">
                {option === "Odd" ? "●" : "●●"}
              </span>

              <span>{option}</span>

              {selected && (
                <span className="predict_the_odd_even_change__check">
                  ✓
                </span>
              )}
            </button>
          );
        })}
      </div>

      {showAnswers && (
        <div className="predict_the_odd_even_change__feedback">
          <span>Correct answer</span>
          <strong>{correctAnswer}</strong>
        </div>
      )}
    </section>
  );
}